/// Known toolsets that are not in the allowlist (case-insensitive).
pub fn toolsets_to_disable(allowed: &[String]) -> Vec<&'static str> {
    let allowed: Vec<String> = allowed
        .iter()
        .map(|a| a.trim().to_ascii_lowercase())
        .collect();
    HERMES_TOOLSETS
        .iter()
        .copied()
        .filter(|t| !allowed.iter().any(|a| a == t))
        .collect()
}

/// Prepended to the Hermes snippet when the MCP server runs on a temporary port.
pub fn fallback_port_warning(configured: u16) -> String {
    format!(
        "# คำเตือน: ตอนนี้ MCP server ใช้พอร์ตชั่วคราว เพราะพอร์ต {configured} ไม่ว่าง
# URL ด้านล่างจะเปลี่ยนเมื่อเปิดแอปใหม่ ให้แก้พอร์ตในหน้าตั้งค่า เปิดแอปใหม่ แล้วคัดลอกข้อความนี้อีกครั้ง

"
    )
}

/// Text the user pastes into Hermes's config. Contains the MCP key.
pub fn hermes_snippet(mcp_url: &str, mcp_key: &str, allowed: &[String], api_base: &str) -> String {
    let disable = toolsets_to_disable(allowed);
    let list = disable
        .iter()
        .map(|t| format!("    - {t}"))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "# 1) ~/.hermes/config.yaml : ให้ Hermes ต่อ MCP server ของแอปนี้ (toolset จะชื่อ mcp-assistant)\n\
#    timeout (วินาที) ต้องไม่น้อยกว่า 450 เพราะคำสั่งอาจรอผู้ใช้อนุมัติได้ 300 วินาทีและรันได้อีก 120 วินาที\n\
#    หมายเหตุ: ระหว่างที่แอปกำลังให้ Hermes ตอบแชตใดอยู่ ทุก session ของ Hermes ที่เรียก MCP server นี้\n\
#    (รวมถึง session อื่นที่คุณเปิดเอง) จะถูกผูกกับแชตนั้น คำสั่งจะรันในโฟลเดอร์ของแชตนั้นและขึ้นในแชตนั้น\n\
mcp_servers:\n  assistant:\n    url: \"{mcp_url}\"\n    headers:\n      Authorization: \"Bearer {mcp_key}\"\n    timeout: 450\n\n\
# 2) ~/.hermes/config.yaml : ปิด toolset ที่รันคำสั่งหรือแตะไฟล์เอง\n\
#    (ทุกตัวที่ไม่อยู่ในรายการอนุญาตของแอป หรือใช้ `hermes tools` ปิดทีละตัว)\n\
agent:\n  disabled_toolsets:\n{list}\n\n\
# 3) ~/.hermes/.env : เปิด API server แล้วรัน `hermes gateway`\n\
#    ตั้ง API_SERVER_KEY เป็นค่าสุ่มของคุณเอง แล้วใส่ค่าเดียวกันในช่อง \"Hermes API key\" ของแอป\n\
API_SERVER_ENABLED=true\n\
API_SERVER_KEY=<ใส่ key ที่คุณตั้งเอง>\n\
# แอปจะเรียก Hermes ที่ {api_base}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn approval_json_shapes() {
        let p = |s: &str| approval_response(serde_json::from_str::<UiApproval>(s).unwrap());
        assert!(matches!(p("\"run\""), Ok(ApprovalResponse::Run)));
        assert!(matches!(p("\"deny\""), Ok(ApprovalResponse::Deny)));
        assert!(
            matches!(p(r#"{"edited":"dir"}"#), Ok(ApprovalResponse::RunEdited(c)) if c == "dir")
        );
        assert!(p("\"maybe\"").is_err());
        assert!(serde_json::from_str::<UiApproval>("42").is_err());
    }

    #[test]
    fn set_secret_rejects_unknown_key_name() {
        assert!(secret_key("grok").is_err());
        assert!(secret_key("").is_err());
        assert!(secret_key("JEV").is_err());
        for (n, k) in [
            ("jev", SecretKey::Jev),
            ("anthropic", SecretKey::Anthropic),
            ("hermes_api", SecretKey::HermesApi),
            ("mcp_hermes", SecretKey::McpHermes),
        ] {
            assert_eq!(secret_key(n).unwrap(), k);
        }
    }

    #[test]
    fn fallback_warning_mentions_port_and_restart() {
        let w = fallback_port_warning(8765);
        assert!(w.contains("8765") && w.contains("พอร์ตชั่วคราว"));
        assert!(w.lines().all(|l| l.is_empty() || l.starts_with('#')));
    }

    #[test]
    fn mcp_key_is_not_writable_from_ui() {
        assert!(writable_secret_key("mcp_hermes").is_err());
        assert!(writable_secret_key("grok").is_err());
        assert_eq!(writable_secret_key("jev").unwrap(), SecretKey::Jev);
        assert_eq!(
            writable_secret_key("hermes_api").unwrap(),
            SecretKey::HermesApi
        );
    }

    #[test]
    fn provider_choice_parses() {
        assert_eq!(provider_choice(None).unwrap(), ProviderChoice::Auto);
        assert_eq!(provider_choice(Some("auto")).unwrap(), ProviderChoice::Auto);
        assert_eq!(
            provider_choice(Some("claude_cli")).unwrap(),
            ProviderChoice::Manual(ProviderId::ClaudeCli)
        );
        assert!(provider_choice(Some("grok")).is_err());
    }

    #[test]
    fn snippet_lists_only_disallowed_toolsets() {
        let allowed: Vec<String> = ["web", "MEMORY", "mcp-assistant"]
            .iter()
            .map(|s| s.to_string())
            .collect();
        let d = toolsets_to_disable(&allowed);
        assert!(d.contains(&"terminal") && d.contains(&"file") && d.contains(&"code_execution"));
        assert!(!d.contains(&"web") && !d.contains(&"memory"));
        let s = hermes_snippet(
            "http://127.0.0.1:8765/mcp/hermes",
            "abc123",
            &allowed,
            "http://127.0.0.1:8642/v1",
        );
        assert!(
            s.contains("mcp_servers:\n  assistant:\n    url: \"http://127.0.0.1:8765/mcp/hermes\"")
        );
        assert!(s.contains("Authorization: \"Bearer abc123\""));
        // Tool calls may wait 300 s for approval and run 120 s.
        assert!(s.contains("      Authorization: \"Bearer abc123\"\n    timeout: 450\n"));
        assert!(s.contains("ทุก session ของ Hermes"));
        assert!(s.contains("    - terminal"));
        assert!(!s.contains("    - web\n"));
        assert!(s.contains("API_SERVER_ENABLED=true"));
    }
}
