//! Pure input parsing for Tauri commands (kept separate so it is unit-tested).

use assistant_core::command_service::ApprovalResponse;
use assistant_core::orchestrator::ProviderChoice;
use assistant_core::settings::SecretKey;
use assistant_core::ProviderId;
use serde::Deserialize;

/// The UI's answer: `"run" | "deny" | {"edited": string}`.
#[derive(Debug, Clone, Deserialize, PartialEq)]
#[serde(untagged)]
pub enum UiApproval {
    Word(String),
    Edited { edited: String },
}

pub fn approval_response(v: UiApproval) -> Result<ApprovalResponse, String> {
    match v {
        UiApproval::Word(w) if w == "run" => Ok(ApprovalResponse::Run),
        UiApproval::Word(w) if w == "deny" => Ok(ApprovalResponse::Deny),
        UiApproval::Word(w) => Err(format!("คำตอบไม่ถูกต้อง: {w}")),
        // A blank edit is turned into Deny by the command service.
        UiApproval::Edited { edited } => Ok(ApprovalResponse::RunEdited(edited)),
    }
}

/// Only the four known key names are accepted.
pub fn secret_key(name: &str) -> Result<SecretKey, String> {
    SecretKey::ALL
        .into_iter()
        .find(|k| k.account() == name)
        .ok_or_else(|| "ไม่รู้จักชื่อ key นี้".to_string())
}

/// A key the UI may set or clear. The MCP key is generated by the app and the
/// running MCP server holds it, so changing it from the UI would desync Hermes.
pub fn writable_secret_key(name: &str) -> Result<SecretKey, String> {
    match secret_key(name)? {
        SecretKey::McpHermes => Err("key ของ MCP แอปสร้างเอง แก้ไขหรือลบจากหน้านี้ไม่ได้".into()),
        k => Ok(k),
    }
}

/// `None` or `"auto"` means Auto; otherwise a provider id.
pub fn provider_choice(p: Option<&str>) -> Result<ProviderChoice, String> {
    match p {
        None | Some("auto") => Ok(ProviderChoice::Auto),
        Some(s) => s.parse::<ProviderId>().map(ProviderChoice::Manual),
    }
}

